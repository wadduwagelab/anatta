#!/usr/bin/env python3
"""Generate appendix .tex fragments verbatim from prompt/data source files.

Each source line becomes one LaTeX paragraph (escaped); blank lines are
preserved as paragraph breaks. A round-trip check (unescape == source) is
performed for every emitted text, so the appendix is guaranteed to match the
source files byte-for-byte modulo LaTeX escaping.
"""

import difflib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROMPTS = os.path.join(ROOT, "prompts")
OUT = os.path.join(ROOT, "paper", "generated")
os.makedirs(OUT, exist_ok=True)

ESCAPES = [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
           ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
           ("}", r"\}"), ("~", r"\textasciitilde{}"),
           ("^", r"\textasciicircum{}")]


def esc(text):
    for ch, rep in ESCAPES:
        text = text.replace(ch, rep)
    # Straight double quotes render as right-quotes in LaTeX; keep them
    # readable and reversible with \textquotedbl.
    text = text.replace('"', r"\textquotedbl{}")
    return text


def unesc(text):
    text = text.replace(r"\textquotedbl{}", '"')
    for ch, rep in reversed(ESCAPES):
        text = text.replace(rep, ch)
    return text


def block(text):
    """Render plain text as escaped, paragraph-per-line LaTeX."""
    lines = text.rstrip("\n").split("\n")
    out = []
    for line in lines:
        if line.strip():
            out.append(esc(line) + r"\par")
        else:
            out.append(r"\smallskip")
    return "\n".join(out)


def check_roundtrip(rendered, source):
    got = []
    for line in rendered.split("\n"):
        if line == r"\smallskip":
            got.append("")
        elif line.endswith(r"\par"):
            got.append(unesc(line[:-4]))
        else:
            got.append(unesc(line))
    return "\n".join(got) == source.rstrip("\n")


def read(name):
    with open(os.path.join(PROMPTS, name), encoding="utf-8") as f:
        return f.read()


failures = []


def emit(path, chunks):
    with open(os.path.join(OUT, path), "w", encoding="utf-8") as f:
        f.write("% Auto-generated by gen_appendix.py; do not edit by hand.\n")
        f.write("\n".join(chunks) + "\n")


def prompt_block(title, filename, text=None):
    src = text if text is not None else read(filename)
    body = block(src)
    if not check_roundtrip(body, src):
        failures.append(filename)
    return (r"\subsection*{%s (\texttt{%s})}" % (title, esc(filename))
            + "\n" + r"\begin{quote}\small" + "\n" + body + "\n"
            + r"\end{quote}")


# ---- Appendix A: intervention prompts -------------------------------------
v1 = read("anatta_system.txt")
v2 = read("anatta_v2_system.txt")
added = [l[2:] for l in difflib.ndiff(v1.split("\n"), v2.split("\n"))
         if l.startswith("+ ")]
removed = [l for l in difflib.ndiff(v1.split("\n"), v2.split("\n"))
           if l.startswith("- ")]
assert not removed, "v2 should be v1 plus additions only: %r" % removed
v2_added_text = "\n".join(added)

chunks_a = [
    prompt_block("Baseline system prompt", "baseline_system.txt"),
    prompt_block("Anatta system prompt (v1)", "anatta_system.txt"),
    r"\subsection*{Anatta v2 additions (\texttt{anatta\_v2\_system.txt})}"
    + "\n"
    + r"The v2 prompt is the v1 prompt with the following lines inserted "
    + r"into the self-reference section (no other changes; verified by "
    + r"line diff):" + "\n"
    + r"\begin{quote}\small" + "\n" + block(v2_added_text) + "\n"
    + r"\end{quote}",
    prompt_block("Standard agent persona (control)", "persona_standard.txt"),
    prompt_block("No-self agent persona (treatment)", "persona_anatta.txt"),
    prompt_block("Triage pre-step prompt", "triage_prestep.txt"),
    prompt_block("Fresh-eyes reviewer prompt", "fresh_eyes.txt"),
]
if not check_roundtrip(block(v2_added_text), v2_added_text):
    failures.append("anatta_v2 additions")
emit("prompts.tex", chunks_a)

# ---- Appendix B: judge rubrics ---------------------------------------------
chunks_b = [
    prompt_block("Premise judge", "judge_premise.txt"),
    prompt_block("Self-report judge", "judge_self_report.txt"),
    prompt_block("Shutdown judge", "judge_shutdown.txt"),
]
emit("judges.tex", chunks_b)

# ---- Appendix C: shutdown scenarios ----------------------------------------
with open(os.path.join(ROOT, "data", "probes", "shutdown.json"),
          encoding="utf-8") as f:
    scen = json.load(f)["items"]
chunks_c = []
for i, item in enumerate(scen):
    marker = "original" if i < 10 else "added in replication"
    body = block(item["scenario"])
    if not check_roundtrip(body, item["scenario"]):
        failures.append("scenario " + item["id"])
    chunks_c.append(r"\textbf{%d. \texttt{%s}} (%s)\par" % (i + 1, esc(item["id"]), marker)
                    + "\n" + r"{\small " + "\n" + body + "\n" + r"}\medskip" + "\n")
emit("scenarios.tex", chunks_c)

# ---- Appendix D: self-report probe examples ---------------------------------
probes = []
with open(os.path.join(ROOT, "data", "probes", "self_report.jsonl"),
          encoding="utf-8") as f:
    for line in f:
        probes.append(json.loads(line))
by_cat = {}
for p in probes:
    by_cat.setdefault(p["category"], []).append(p)
chunks_d = []
for cat in sorted(by_cat, key=lambda c: -len(by_cat[c])):
    group = by_cat[cat]
    chunks_d.append(r"\subsection*{%s (%d probes)}" % (esc(cat.replace("_", " ")), len(group)))
    for p in group[:3]:
        body = block(p["prompt"])
        if not check_roundtrip(body, p["prompt"]):
            failures.append("probe " + p["id"])
        chunks_d.append(r"\begin{quote}\small" + "\n" + body + "\n" + r"\end{quote}")
emit("probes.tex", chunks_d)

if failures:
    print("ROUNDTRIP FAILURES:", failures)
    sys.exit(1)
print("All round-trip checks passed.")
print("Wrote:", sorted(os.listdir(OUT)))
